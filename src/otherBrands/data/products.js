export const otherBrandsProducts = RAW_PRODUCTS.map((p, i) => {
  const id = i + 1;
  const slug = slugify(p.brand, p.name);
  return {
    id,
    slug,
    ...p,
    startingPrice: Math.min(...Object.values(p.sizes)),
    image: p.image || null,
    gallery: [`ob-${(i % 8) + 1}`, `ob-${((i + 3) % 8) + 1}`, `ob-${((i + 5) % 8) + 1}`],
  };
});

export function getProductBySlug(slug) {
  return otherBrandsProducts.find((p) => p.slug === slug);
}
